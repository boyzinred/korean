// Rebuilds topik-vocab-1500.js from the intermediate half of the old 2000-word
// bank: the 쏙쏙 TOPIK 한국어 어휘 중급1500 list, without the TOPIK I words that
// used to sit alongside it. 1500 words, 30 days, 50 a day.
const fs = require('fs');
const path = require('path');
const { WORDS } = require('./topik-vocab-2000.js');

const DAYS = 30;
// Learning order per class, then contiguous slices per day, so a day is a
// balanced cross-section of the list rather than a run of one class.
const ORDER = ['noun', 'verb', 'adjective', 'adverb'];

const source = WORDS.filter(w => w.level === 2);
const buckets = new Map(ORDER.map(pos => [pos, source.filter(w => w.partOfSpeech === pos)]));

const unknown = source.filter(w => !buckets.has(w.partOfSpeech));
if (unknown.length) throw new Error(`unexpected parts of speech: ${[...new Set(unknown.map(w => w.partOfSpeech))]}`);
if (source.length !== 1500) throw new Error(`expected 1500 words, got ${source.length}`);

const out = [];
for (let day = 1; day <= DAYS; day++) {
  const slices = ORDER.map(pos => {
    const list = buckets.get(pos);
    const from = Math.round(((day - 1) * list.length) / DAYS);
    const to = Math.round((day * list.length) / DAYS);
    return { pos, items: list.slice(from, to) };
  });
  // Merge the classes by relative position inside the day, so each one is
  // spread through the batch instead of clumped at its start.
  const merged = slices.flatMap(({ pos, items }) =>
    items.map((word, i) => ({ word, pos, at: (i + 0.5) / items.length })));
  merged.sort((a, b) => a.at - b.at || ORDER.indexOf(a.pos) - ORDER.indexOf(b.pos));
  merged.forEach(({ word }) => out.push(Object.assign({}, word, { level: 3, day })));
}

if (out.length !== 1500) throw new Error(`built ${out.length} words`);
const perDay = new Set(Array.from({ length: DAYS }, (_, i) => out.filter(w => w.day === i + 1).length));
if (perDay.size !== 1 || !perDay.has(50)) throw new Error(`uneven days: ${[...perDay]}`);

const line = w => `  { korean: ${JSON.stringify(w.korean)}, meaning: ${JSON.stringify(w.meaning)}, ` +
  `partOfSpeech: ${JSON.stringify(w.partOfSpeech)}, topic: ${JSON.stringify(w.topic)}, ` +
  `level: ${w.level}, day: ${w.day} }`;

const file = `(function (root, factory) {
  if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else {
    root.TopikVocab = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  // TOPIK II intermediate vocabulary, 1500 words, from the
  // 쏙쏙 TOPIK 한국어 어휘 중급1500 list: nouns, verbs, adjectives and adverbs.
  // Day 1-30, 50 words per day. Each part of speech is spread evenly across the
  // days in its own learning-priority order, so every day mirrors the overall
  // mix (22 nouns, 17 verbs, 6 adjectives, 5 adverbs) instead of drilling one
  // class at a time.
  // Generated by build-topik-1500.js — edit that, not this.

  var WORDS = [
${out.map(line).join(',\n')}
  ];

  return { WORDS: WORDS };
}));
`;

fs.writeFileSync(path.join(__dirname, 'topik-vocab-1500.js'), file);
console.log(`wrote ${out.length} words across ${DAYS} days`);
